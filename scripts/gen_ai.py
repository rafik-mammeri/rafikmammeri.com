"""Make the built site easy for AI agents (Claude, ChatGPT, Perplexity...) to read.

Run by scripts/build.sh after the Zensical builds, on site/:
- a clean Markdown twin of each page, next to its HTML (site/experience/index.md...), in English
  and in French, without menus, scripts or layout;
- site/llms-full.txt: the whole English site in one Markdown file;
- site/llms.txt: who Rafik is in a few facts, the positions, the pages and the articles
  (the llms.txt convention, https://llmstxt.org);
- a <lastmod> date for each page in the sitemaps, from the last commit that touched its source.

The pages are the source of truth. The one hand-written part, who Rafik is in a few facts (the
llms.txt summary and the schema.org Person), lives in ai-profile.md at the root of the repo:
`--person` (run before the builds) turns it into overrides/partials/ai-person.html.

Standard library only.
"""
from __future__ import annotations

import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
BASE = "https://www.rafikmammeri.com"


PROFILE = ROOT / "ai-profile.md"
PERSON = ROOT / "overrides" / "partials" / "ai-person.html"


def profile() -> dict:
    """ai-profile.md: the only hand-written part of the AI layer ("key: value", lists as "  - x")."""
    data, key = {}, None
    for line in PROFILE.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if m:
            key = m.group(1)
            data[key] = m.group(2).strip() or []
        elif key and re.match(r"^\s+- ", line) and isinstance(data.get(key), list):
            data[key].append(line.strip()[2:].strip())
    return data


def person_jsonld() -> None:
    """The schema.org Person for the home and Experience pages, from ai-profile.md."""
    import json
    p = profile()
    person = {
        "@context": "https://schema.org", "@type": "Person", "@id": f"{BASE}/#person",
        "name": p["name"], "jobTitle": p["job_title"], "description": p["description"],
        "url": f"{BASE}/", "image": f"{BASE}/assets/og-card.png",
        "worksFor": {"@type": "Organization", "name": p["employer"]},
        "address": {"@type": "PostalAddress", "addressLocality": p["city"], "addressCountry": p["country"]},
        "alumniOf": [{"@type": "CollegeOrUniversity", "name": n} for n in p["education"]],
        "knowsAbout": p["expertise"], "sameAs": p["profiles"],
    }
    PERSON.parent.mkdir(parents=True, exist_ok=True)
    PERSON.write_text("{#- Generated by scripts/gen_ai.py from ai-profile.md; edit that file. -#}\n"
                      '<script type="application/ld+json">\n' + json.dumps(person, ensure_ascii=False, indent=2)
                      + "\n</script>\n", encoding="utf-8")


def split(text: str) -> tuple[str, str]:
    m = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    return (m.group(1), text[m.end():]) if m else ("", text)


def field(fm: str, key: str) -> str:
    m = re.search(rf'^{key}:\s*"?(.*?)"?\s*$', fm, re.M)
    return m.group(1) if m else ""


def clean(body: str, base: str = BASE) -> str:
    """Zensical Markdown to plain Markdown: no attribute lists, icons, wrappers or admonition syntax."""
    out, terms, quote, stack = [], [], False, None
    for line in body.splitlines():
        t = line.strip()
        # a project's technologies: one line, "Stack: LangGraph, Anthropic, ..."
        if t.startswith('<div class="rm-stack"'):
            stack = []
            continue
        if stack is not None:
            if t == "</div>":
                out.append("**Stack:** " + ", ".join(stack))
                stack = None
            elif t.startswith("- "):
                stack.append(re.sub(r"^:[\w-]+:\s*", "", t[2:]).strip())
            continue
        if re.fullmatch(r"\{[^}]*\}", t) or re.fullmatch(r"</?div[^>]*>", t):
            continue
        m = re.match(r"\*\[(.+?)\]:\s*(.+)", t)
        if m:
            terms.append(f"- **{m.group(1)}**: {m.group(2)}")
            continue
        m = re.match(r'(!!!|\?\?\?\+?)\s+\w+(?:\s+inline(?:\s+end)?)?(?:\s+"(.*)")?', t)
        if m:
            out.append(f"> **{m.group(2)}**" if m.group(2) else ">")
            quote = True
            continue
        if quote:
            if line.startswith("    ") or not t:
                out.append("> " + line[4:] if t else ">")
                continue
            quote = False
        line = re.sub(r"\s*\{[ .#:][^}]*\}", "", line)            # { #id data-x="…" } and { .class }
        line = re.sub(r":[a-z0-9]+(?:-[a-z0-9]+)*:\s?", "", line)  # :logos-python: and other icons
        line = re.sub(r"==(.+?)==", r"\1", line)
        out.append(line)
    text = "\n".join(out)
    # links between pages become full addresses (about.md -> https://…/about/)
    text = re.sub(r"\]\((?!https?:|#|mailto:)([\w/-]+?)(?:/index)?\.md(#[\w-]+)?\)",
                  lambda m: f"]({base}/{m.group(1).strip('/')}/{m.group(2) or ''})", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    if terms:
        text += "\n## Terms\n\n" + "\n".join(terms) + "\n"
    return text


def home(lang: str) -> str:
    """The homepage is built from its front matter: the statement and what Rafik is doing now."""
    src = ROOT / ("docs" if lang == "en" else "docs-fr") / "index.md"
    fm, body = split(src.read_text(encoding="utf-8"))
    head, now = fm.split("\n  rows:\n", 1)
    statement = " ".join(re.findall(r'^\s+- "(.*)"', head.split("statement:", 1)[1], re.M))
    role = field(fm, "  role") or "Lead AI Engineer"
    prefix = "" if lang == "en" else "/fr"
    lines = [f"# Rafik Mammeri, {role}", "", statement, ""]
    for block in now.split('- label: "')[1:]:
        label = block.split('"', 1)[0]
        text = re.search(r'text: "([^"]+)"', block).group(1)
        href = re.search(r'^\s+href: "([^"]+)"', block, re.M)
        more = f" [{'More' if lang == 'en' else 'Lire'}]({BASE}{prefix}/{href.group(1)})" if href else ""
        extra = re.search(r'^\s+more: "([^"]+)"', block, re.M)
        extra_href = re.search(r'^\s+more_href: "([^"]+)"', block, re.M)
        if extra and extra_href:
            text += f", [{extra.group(1).lstrip('… ')}]({BASE}{prefix}/{extra_href.group(1)})"
        lines.append(f"- **{label}**: {text}{more}")
    lines += ["", clean(body, BASE + prefix)]
    return "\n".join(lines).strip() + "\n"


def page(src: Path, base: str = BASE) -> tuple[str, str, str]:
    fm, body = split(src.read_text(encoding="utf-8"))
    title = field(fm, "title")
    text = clean(body, base)
    if not text.lstrip().startswith("# "):
        text = f"# {title}\n\n" + text
    return title, field(fm, "description"), text


def pages(lang: str) -> list[tuple[str, str, str, str]]:
    """(url, title, description, markdown) for every page worth reading, in reading order."""
    d = ROOT / ("docs" if lang == "en" else "docs-fr")
    prefix = "" if lang == "en" else "/fr"
    out = [(f"{BASE}{prefix}/", "Home" if lang == "en" else "Accueil",
            "Who Rafik is, his view of AI agents, what he does now and before." if lang == "en" else "", home(lang))]
    for name in ("experience",):
        if (d / f"{name}.md").exists():
            out.append((f"{BASE}{prefix}/{name}/",) + page(d / f"{name}.md", BASE + prefix))
    if lang == "en":
        for src in sorted((ROOT / "docs" / "writing").glob("*.md"), reverse=True):
            fm, _ = split(src.read_text(encoding="utf-8"))
            if field(fm, "template") == "article.html" and field(fm, "demo") != "true":
                t, desc, md = page(src)
                md = md.replace(f"# {t}\n", f"# {t}\n\nPublished {src.stem[:10]} · by Rafik Mammeri\n", 1)
                out.append((f"{BASE}/writing/{src.stem}/", t, desc, md))
    return out


def write_twins(lang: str, items) -> None:
    for url, _, _, md in items:
        rel = url[len(BASE):].strip("/")
        target = SITE / rel / "index.md" if rel else SITE / "index.md"
        if target.parent.exists():
            target.write_text(md, encoding="utf-8")


def positions() -> list[str]:
    text = (ROOT / "docs" / "experience.md").read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'^## (?::[\w-]+: )?(.+?) \{ #([\w-]+)([^}]*)\}\s*\n+(.+?)\n', text, re.M):
        name, pid, attrs, meta = m.groups()
        role = meta.split("·")[0].strip()
        years = re.search(r'data-years="([^"]+)"', attrs).group(1)
        key = re.search(r'data-key="([^"]+)"', attrs).group(1)
        lead = re.search(r'data-lead="([^"]+)"', attrs)
        bits = ([lead.group(1)] if lead else []) + [key]
        out.append(f"- **{name}**, {role}, {years}: {'. '.join(bits)}. [{name}]({BASE}/experience/#{pid})")
    return out


def host(url: str) -> str:
    return re.sub(r"^https?://(www\.)?", "", url).split("/")[0]


def llms(items) -> str:
    p = profile()
    lines = [
        f"# {p['name']}",
        "",
        f"> {p['summary']}",
        "",
        "Every page below also exists as plain Markdown: add `index.md` to its address. The whole site "
        f"in one file: {BASE}/llms-full.txt.",
        "",
        "## Positions",
        "",
        *positions(),
        "",
        "## Pages",
        "",
    ]
    for url, title, desc, _ in items:
        if "/writing/" not in url:
            lines.append(f"- [{title}]({url}index.md)" + (f": {desc}" if desc else ""))
    lines += ["", "## Articles", ""]
    for url, title, desc, _ in items:
        if "/writing/" in url:
            lines.append(f"- [{title}]({url}index.md)" + (f": {desc}" if desc else ""))
    lines += ["", "## Optional", "",
              f"- [Full site in one file]({BASE}/llms-full.txt)",
              f"- [RSS feed of the articles]({BASE}/feed.xml)",
              *[f"- [{host(u)}]({u})" for u in p["profiles"]]]
    return "\n".join(lines) + "\n"


def full(items) -> str:
    parts = [f"# Rafik Mammeri, the whole site\n\nSource: {BASE}/ (Markdown versions of each page; "
             f"generated at build time from the site itself).\n"]
    for url, _, _, md in items:
        parts.append(f"\n---\n\nSource: {url}\n\n{md}")
    return "".join(parts)


def last_change(path: Path) -> str:
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", str(path)], cwd=ROOT,
                             capture_output=True, text=True, timeout=10).stdout.strip()
        return out or date.today().isoformat()
    except Exception:
        return date.today().isoformat()


def lastmod(sitemap: Path, docs: Path, items=()) -> None:
    if not sitemap.exists():
        return
    xml = sitemap.read_text(encoding="utf-8")
    # every page with a Markdown twin is listed, even if the theme's sitemap left one out
    for url, *_ in items:
        if f"<loc>{url}</loc>" not in xml:
            xml = xml.replace("</urlset>", f"    <url>\n        <loc>{url}</loc>\n    </url>\n</urlset>")

    def add(m):
        loc = m.group(1)
        rel = re.sub(r"^https?://[^/]+/(fr/)?", "", loc).strip("/")
        src = docs / (f"{rel}.md" if rel else "index.md")
        if not src.exists() and rel.startswith("writing/"):
            src = ROOT / "docs" / f"{rel}.md"
        when = last_change(src) if src.exists() else date.today().isoformat()
        return f"<loc>{loc}</loc>\n        <lastmod>{when}</lastmod>"

    xml = re.sub(r"<loc>([^<]+)</loc>(?!\s*<lastmod>)", add, xml)
    sitemap.write_text(xml, encoding="utf-8")


def main() -> None:
    import sys
    if "--person" in sys.argv:  # before the builds: the template includes the generated Person
        person_jsonld()
        print("AI profile: structured data written from ai-profile.md")
        return
    en = pages("en")
    write_twins("en", en)
    (SITE / "llms-full.txt").write_text(full(en), encoding="utf-8")
    (SITE / "llms.txt").write_text(llms(en), encoding="utf-8")
    lastmod(SITE / "sitemap.xml", ROOT / "docs", en)
    print(f"AI-readable: {len(en)} pages as Markdown, llms.txt, llms-full.txt, sitemap dates")


if __name__ == "__main__":
    main()
